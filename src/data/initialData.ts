const ONES = ['', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten', 'eleven', 'twelve', 'thirteen', 'fourteen', 'fifteen', 'sixteen', 'seventeen', 'eighteen', 'nineteen'];
const TENS = ['', '', 'twenty', 'thirty', 'forty', 'fifty', 'sixty', 'seventy', 'eighty', 'ninety'];

function convertLessThanOneThousand(num: number): string {
  if (num === 0) return '';
  if (num < 20) return ONES[num];
  if (num < 100) {
    return TENS[Math.floor(num / 10)] + (num % 10 !== 0 ? ' ' + ONES[num % 10] : '');
  }
  return ONES[Math.floor(num / 100)] + ' hundred' + (num % 100 !== 0 ? ' ' + convertLessThanOneThousand(num % 100) : '');
}

export function numberToWordsBDT(amount: number): string {
  const n = Math.round(Math.abs(amount));
  if (n === 0) return 'zero Taka Only';
  const parts: string[] = [];
  let rem = n;
  if (rem >= 100000) {
    const lakh = Math.floor(rem / 100000);
    parts.push(convertLessThanOneThousand(lakh) + ' lakh');
    rem %= 100000;
  }
  if (rem >= 1000) {
    const thousand = Math.floor(rem / 1000);
    parts.push(convertLessThanOneThousand(thousand) + ' thousand');
    rem %= 1000;
  }
  if (rem > 0) {
    parts.push(convertLessThanOneThousand(rem));
  }
  return parts.join(' ').trim() + ' Taka Only';
}
