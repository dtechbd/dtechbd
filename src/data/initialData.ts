// Helper to convert SVG to data URI so images never fail offline or in sandbox
function svgDataUrl(bg: string, fg: string, label: string, subLabel = ''): string {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="320" height="240" viewBox="0 0 320 240">
    <rect width="320" height="240" rx="12" fill="${bg}"/>
    <rect x="20" y="20" width="280" height="200" rx="8" fill="none" stroke="${fg}" stroke-opacity="0.25" stroke-width="2"/>
    <text x="160" y="112" font-family="Plus Jakarta Sans, sans-serif" font-size="22" font-weight="700" fill="${fg}" text-anchor="middle">${label}</text>
    <text x="160" y="144" font-family="JetBrains Mono, monospace" font-size="13" font-weight="500" fill="${fg}" fill-opacity="0.8" text-anchor="middle">${subLabel}</text>
  </svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

